// Writes supabase/seed/faculty.sql from src/lib/data/faculty.ts, so the database and
// the site's fallback list stay the same. Run: node scripts/faculty-seed.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { sampleFaculty } = await import(join(root, "src/lib/data/faculty.ts"));

const sql = (value) => (value === null ? "null" : `'${String(value).replace(/'/g, "''")}'`);
const values = sampleFaculty
  .map((f) => `  (${sql(f.name)}, ${sql(f.designation)}, ${sql(f.room)}, ${sql(f.email)}, ${f.position})`)
  .join(",\n");

writeFileSync(
  join(root, "supabase/seed/faculty.sql"),
  `-- CSE faculty at IUB, from https://iub.ac.bd/directory/cse?type=departments (retrieved
-- 28 Sep 2026). Generated by scripts/faculty-seed.mjs from src/lib/data/faculty.ts.
-- Re-running updates names, designations, rooms and order; login emails and
-- notification settings set in the database are kept.
insert into public.faculty (name, designation, room, email, position) values
${values}
on conflict (email) do update set
  name = excluded.name,
  designation = excluded.designation,
  room = excluded.room,
  position = excluded.position;
`,
);
console.log(`Wrote ${sampleFaculty.length} faculty to supabase/seed/faculty.sql`);
