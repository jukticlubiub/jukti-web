// Writes supabase/seed/content.sql from the files in src/lib/data/ (team, alumni, the
// About story, developers, the board term and social links), so the admin panel starts
// with what the site shows today. Each table is only filled if it's still empty, so
// running it again never duplicates anything. Run: node scripts/content-seed.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const load = (file) => import(join(root, "src/lib/data", file));
const { teamMembers, boardTerm } = await load("team.ts");
const { alumni } = await load("alumni.ts");
const { storyChapters } = await load("story.ts");
const { developers } = await load("developers.ts");

const sql = (v) => (v === null || v === undefined ? "null" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const json = (v) => `${sql(JSON.stringify(v))}::jsonb`;

function fill(table, columns, rows) {
  if (rows.length === 0) return `-- ${table}: nothing to add\n`;
  return `insert into public.${table} (${columns.join(", ")})
select * from (values
${rows.map((r) => `  (${r.join(", ")})`).join(",\n")}
) as v(${columns.join(", ")})
where not exists (select 1 from public.${table});
`;
}

// Placeholder cards ("Executive 05", "Alumni 03") aren't carried over.
const realTeam = teamMembers.filter((m) => m.role !== "Designation" && !/^(Advisor|Executive) \d+$/.test(m.name));
const position = { advisor: 0, executive: 0 };
const team = realTeam.map((m) => [sql(m.kind), sql(m.name), sql(m.role), sql(m.photo), sql(m.linkedin), position[m.kind]++]);
const realAlumni = alumni.filter((a) => !/^Alumni \d+$/.test(a.name));

const out = `-- Generated by scripts/content-seed.mjs from src/lib/data/. Fills each table only if empty.
-- After this, edit everything in the admin panel (/admin).

${fill("team_members", ["kind", "name", "role", "photo_url", "linkedin", "position"], team)}
${fill("alumni", ["name", "role", "term", "photo_url", "linkedin", "position"], realAlumni.map((a, i) => [sql(a.name), sql(a.role), sql(a.term), sql(a.photo), sql(a.linkedin), i]))}
${fill(
  "story_chapters",
  ["slug", "kicker", "title", "body", "badge", "photo_hint", "photo_url", "photo_alt", "link_href", "link_label", "position"],
  storyChapters.map((c, i) => [sql(c.id), sql(c.kicker), sql(c.title), sql(c.body), sql(c.badge), sql(c.photoHint), sql(c.photo?.src), sql(c.photo?.alt ?? ""), sql(c.link?.href), sql(c.link?.label), i]),
)}
${fill(
  "developers",
  ["name", "role", "designation", "photo_url", "socials", "position"],
  developers.map((d, i) => [sql(d.name), sql(d.role), sql(d.designation), sql(d.photo), json(Object.fromEntries(Object.entries(d.socials).filter(([, v]) => v))), i]),
)}
insert into public.site_settings (key, value) values
  ('team.board_term', ${json(boardTerm)}),
  ('socials', ${json({ facebook: "https://www.facebook.com/jukti.cse.iub", instagram: "https://www.instagram.com/jukti.iub", linkedin: "https://www.linkedin.com/company/jukti-iub", email: "jukti.iub@gmail.com" })})
on conflict (key) do nothing;
`;

writeFileSync(join(root, "supabase/seed/content.sql"), out);
console.log(`Wrote supabase/seed/content.sql: ${team.length} team, ${realAlumni.length} alumni, ${storyChapters.length} chapters, ${developers.length} developers`);
